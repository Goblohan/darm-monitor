"""Experimental exact-head online witness gate; additive to existing E38 profile.

The network endpoint and verification keys MUST be consumer provisioned. A
successful query proves only the authority's latest acknowledged state at its
reply, not Guard complete mediation or the absence of later concurrent effects.
"""
from __future__ import annotations

import json
import secrets
from typing import Callable

from cryptography.exceptions import InvalidSignature

from guard_audit_bridge import _parse_jsonl
from guard_witness_bridge import _canonical, verify_trusted_witness
from verifier import Verdict
from witness_authority import ONLINE_DOMAIN, WitnessRefusal, _load, _valid_cp


def verify_online_exact_head(response: bytes, nonce: str, audit: bytes,
                             witness_public, guard_public_ring) -> bool:
    """Check a nonce-bound signed live answer and exact audited snapshot head."""
    try:
        obj = _load(response, maximum=16_384)
        if type(obj) is not dict or set(obj) != {"v", "nonce", "witness", "signature"}:
            return False
        if type(obj["v"]) is not int or obj["v"] != 2 or obj["nonce"] != nonce:
            return False
        sig = obj["signature"]
        if not (isinstance(sig, str) and len(sig) == 128
                and all(c in "0123456789abcdef" for c in sig)):
            return False
        body = {k: v for k, v in obj.items() if k != "signature"}
        witness_public.verify(bytes.fromhex(sig), ONLINE_DOMAIN + _canonical(body))
        raw_receipt = _canonical(obj["witness"])
        verified = verify_trusted_witness(raw_receipt, witness_public, guard_public_ring)
        if not verified.verified:
            return False
        rows = _parse_jsonl(audit)
        return (bool(rows) and len(rows) == verified.count
                and rows[0].get("entry_hash") == verified.genesis
                and rows[-1].get("entry_hash") == verified.head)
    except (WitnessRefusal, UnicodeError, ValueError, TypeError, AttributeError,
            KeyError, OverflowError, RecursionError, InvalidSignature):
        return False


class ExactHeadOnlineGate:
    """A strictly stronger, online-only variant of the current pinned profile.

    No fallback to the offline pin when the live witness query fails. The
    trusted caller must configure fetch_challenge; an agent cannot choose keys.
    """
    def __init__(self, pinned_verifier, fetch_challenge: Callable[[bytes], bytes]):
        from correspondence_runtime import PinnedRelianceVerifier
        if not isinstance(pinned_verifier, PinnedRelianceVerifier):
            raise ValueError("pinned-verifier-required")
        if not callable(fetch_challenge):
            raise ValueError("trusted-witness-transport-required")
        self.pinned = pinned_verifier
        self.fetch_challenge = fetch_challenge

    def decide_json(self, request: bytes, now: int, attestation: bytes,
                    content: bytes, audit: bytes, checkpoints: bytes) -> Verdict:
        # Live nonce generated by the consumer, never supplied by the agent.
        nonce = secrets.token_hex(32)
        try:
            response = self.fetch_challenge(_canonical({"nonce": nonce}))
            if not verify_online_exact_head(response, nonce, audit,
                    self.pinned.store.witness_public, self.pinned.store.guard_public_ring):
                raise WitnessRefusal("live-head-not-acknowledged")
        except (OSError, TimeoutError, ValueError, TypeError, AttributeError,
                UnicodeError, RecursionError) as exc:
            return Verdict(False, ("witness:online-check-failed",), (), (), False)
        # Underlying verifier still checks evidence, the signed full snapshot,
        # the protected local pin, consumer claim/policy, and semantic warrants.
        return self.pinned.decide_json(request, now, attestation, content, audit, checkpoints)
