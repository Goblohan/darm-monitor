/* darm_shim.c — C FFI Bridge for AgentSandbox Profile
 *
 * This file wraps Lean-exported functions with a C-friendly API.
 * It handles:
 *   - Lean runtime initialization
 *   - String marshaling (C string ↔ Lean object)
 *   - State packing/unpacking
 *   - Error handling (all errors are fail-closed)
 *
 * Build: compile with leanc (Lean's C compiler) or link against
 *        the Lean runtime and the AgentSandbox shared library.
 */

#include "darm_shim.h"
#include <lean/lean.h>
#include <string.h>

/* ============================================================================
 * FORWARD DECLARATIONS (Lean exported functions)
 * ============================================================================ */

/* These functions are generated by Lean's `@[export]` mechanism.
 * Their signatures must match exactly what Lean emits. */

extern uint64_t lean_darm_init_state(uint8_t task_id);
extern uint8_t  lean_darm_decide(lean_obj_arg method,
                                 lean_obj_arg path,
                                 uint16_t cap_mask,
                                 uint16_t policy_mask,
                                 uint8_t suspended);
extern uint16_t lean_darm_init_cap_mask(uint8_t task_id);
extern uint16_t lean_darm_init_policy_mask(uint8_t task_id);

/* ============================================================================
 * RUNTIME INITIALIZATION
 * ============================================================================ */

static int g_darm_runtime_initialized = 0;

void darm_init_runtime(void) {
    if (!g_darm_runtime_initialized) {
        lean_initialize_runtime_module();
        g_darm_runtime_initialized = 1;
    }
}

void darm_shutdown(void) {
    if (g_darm_runtime_initialized) {
        /* Lean 4 does not expose a public shutdown API in all versions.
         * This is a no-op in production; the OS cleans up at exit. */
        g_darm_runtime_initialized = 0;
    }
}

/* ============================================================================
 * STATE INITIALIZATION
 * ============================================================================ */

void darm_init_state(uint8_t task_id, DarmState* out_state) {
    if (!out_state) return;

    uint64_t packed = lean_darm_init_state(task_id);

    out_state->cap_mask    = (uint16_t)(packed & 0xFFFF);
    out_state->policy_mask = (uint16_t)((packed >> 16) & 0xFFFF);
    out_state->op_state    = (uint32_t)((packed >> 32) & 0xFFFFFFFF);
    out_state->suspended   = (uint8_t)((packed >> 63) & 1);
}

uint16_t darm_init_cap_mask(uint8_t task_id) {
    return lean_darm_init_cap_mask(task_id);
}

uint16_t darm_init_policy_mask(uint8_t task_id) {
    return lean_darm_init_policy_mask(task_id);
}

/* ============================================================================
 * DECISION
 * ============================================================================ */

uint8_t darm_decide(const char* method,
                    const char* path,
                    const DarmState* state) {
    if (!state) {
        /* Null state is a deployment bug — fail closed. */
        return 0; /* BLOCKED */
    }
    return darm_decide_raw(method, path,
                           state->cap_mask,
                           state->policy_mask,
                           state->suspended);
}

uint8_t darm_decide_raw(const char* method_c,
                        const char* path_c,
                        uint16_t cap_mask,
                        uint16_t policy_mask,
                        uint8_t suspended) {
    if (!method_c || !path_c) {
        /* Null strings are a deployment bug — fail closed. */
        return 0; /* BLOCKED */
    }

    /* Convert C strings to Lean objects. lean_mk_string copies the data. */
    lean_obj_res method = lean_mk_string(method_c);
    lean_obj_res path   = lean_mk_string(path_c);

    /* Call the verified Lean function. */
    uint8_t result = lean_darm_decide(method, path, cap_mask, policy_mask, suspended);

    /* Decrement reference counts. Lean uses reference counting. */
    lean_dec(method);
    lean_dec(path);

    /* result: 0 = BLOCK, 1 = ALLOW, 2 = UNKNOWN
     * The Rust shim treats UNKNOWN (2) as BLOCKED. */
    return result;
}
